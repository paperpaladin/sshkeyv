pub fn sha512(data: &[u8]) -> [u8; 64] {
    let mut h: [u64; 8] = [
        0x6a09e667f3bcc908,
        0xbb67ae8584caa73b,
        0x3c6ef372fe94f82b,
        0xa54ff53a5f1d36f1,
        0x510e527fade682d1,
        0x9b05688c2b3e6c1f,
        0x1f83d9abfb41bd6b,
        0x5be0cd19137e2179,
    ];
    for block in pad(data, 128, 16).chunks(128) {
        let mut w = [0u64; 80];
        for i in 0..16 {
            let mut v = 0u64;
            for j in 0..8 {
                v = (v << 8) | block[8 * i + j] as u64;
            }
            w[i] = v;
        }
        for i in 16..80 {
            let s0 = w[i - 15].rotate_right(1)
                ^ w[i - 15].rotate_right(8)
                ^ (w[i - 15] >> 7);
            let s1 = w[i - 2].rotate_right(19)
                ^ w[i - 2].rotate_right(61)
                ^ (w[i - 2] >> 6);
            w[i] = w[i - 16]
                .wrapping_add(s0)
                .wrapping_add(w[i - 7])
                .wrapping_add(s1);
        }
        let mut v = h;
        for i in 0..80 {
            let s1 = v[4].rotate_right(14)
                ^ v[4].rotate_right(18)
                ^ v[4].rotate_right(41);
            let ch = (v[4] & v[5]) ^ (!v[4] & v[6]);
            let t1 = v[7]
                .wrapping_add(s1)
                .wrapping_add(ch)
                .wrapping_add(K512[i])
                .wrapping_add(w[i]);
            let s0 = v[0].rotate_right(28)
                ^ v[0].rotate_right(34)
                ^ v[0].rotate_right(39);
            let maj = (v[0] & v[1]) ^ (v[0] & v[2]) ^ (v[1] & v[2]);
            let t2 = s0.wrapping_add(maj);
            v[7] = v[6];
            v[6] = v[5];
            v[5] = v[4];
            v[4] = v[3].wrapping_add(t1);
            v[3] = v[2];
            v[2] = v[1];
            v[1] = v[0];
            v[0] = t1.wrapping_add(t2);
        }
        for i in 0..8 {
            h[i] = h[i].wrapping_add(v[i]);
        }
    }
    let mut out = [0u8; 64];
    for i in 0..8 {
        out[8 * i..8 * i + 8].copy_from_slice(&h[i].to_be_bytes());
    }
    out
}

/// The padded message: a 0x80 byte, zeros, then the bit length in the last
/// `lenbytes` bytes of the final block.
///
/// The Vec is exactly the padded length. That is deliberate and it is
/// METHOD's buffer section rather than tidiness: a buffer longer than its
/// data moves the bounds check away from the end of the data, and the
/// natural way to write this is to round the input up to a block boundary
/// and leave the slack, which is the same blind spot.
fn pad(data: &[u8], block: usize, lenbytes: usize) -> Vec<u8> {
    let bitlen = (data.len() as u128) * 8;
    let mut n = data.len() + 1;
    while (n + lenbytes) % block != 0 {
        n += 1;
    }
    let total = n + lenbytes;
    let mut out = Vec::with_capacity(total);
    out.extend_from_slice(data);
    out.push(0x80);
    out.resize(n, 0);
    let be = bitlen.to_be_bytes();
    out.extend_from_slice(&be[16 - lenbytes..]);
    debug_assert_eq!(out.len(), total);
    debug_assert_eq!(out.capacity(), total);
    out
}

// MD5, from RFC 1321. It is here because ssh-keygen -l -E md5 still
// prints it and because a deployment that recorded its host key
// fingerprints before OpenSSH 6.8 recorded them in this form. Nothing in
// this program uses MD5 to decide anything.
//
// Little-endian where SHA is big-endian, which is the only interesting
// thing about writing it after the other two.

const S: [u32; 64] = [
    7, 12, 17, 22, 7, 12, 17, 22, 7, 12, 17, 22, 7, 12, 17, 22, 5, 9, 14,
    20, 5, 9, 14, 20, 5, 9, 14, 20, 5, 9, 14, 20, 4, 11, 16, 23, 4, 11, 16,
    23, 4, 11, 16, 23, 4, 11, 16, 23, 6, 10, 15, 21, 6, 10, 15, 21, 6, 10,
    15, 21, 6, 10, 15, 21,
];

