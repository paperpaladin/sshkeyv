// SHA-256 and SHA-512, from FIPS 180-4.
//
// They are here because the fingerprint everyone reads is a SHA-256 of the
// key blob, and because the signature algorithms name a digest: ssh-rsa is
// SHA-1, rsa-sha2-256 and ecdsa-sha2-nistp256 are SHA-256, rsa-sha2-512
// and the SSHSIG default are SHA-512.
//
// Both are the same construction over different word sizes and constants,
// but writing one generic over a word trait costs more than writing two,
// so there are two.

